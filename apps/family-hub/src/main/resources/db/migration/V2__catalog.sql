-- Things that can be bought: food, household, DIY, garden, clothing. Items of kind INGREDIENT can
-- also be used in recipes.
CREATE TABLE item (
    id               INTEGER PRIMARY KEY,
    name             TEXT    NOT NULL UNIQUE COLLATE NOCASE,
    kind             TEXT    NOT NULL CHECK (kind IN ('GOODS', 'INGREDIENT')),
    store_type       TEXT    NOT NULL,
    aisle            TEXT    NOT NULL,
    unit             TEXT    NOT NULL,
    unit_price_cents INTEGER CHECK (unit_price_cents >= 0)
);

